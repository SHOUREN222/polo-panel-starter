use Stancl\Tenancy\UUIDGenerator;

$parentDomain = trim((string) env('TENANCY_PARENT_DOMAIN', ''));
$appHost = parse_url((string) env('APP_URL', 'http://localhost'), PHP_URL_HOST);
$centralDomains = array_values(array_unique(array_filter([
    '127.0.0.1',
    'localhost',
    is_string($appHost) ? strtolower($appHost) : null,
    $parentDomain !== '' ? strtolower($parentDomain) : null,
    ...array_map(
        fn (string $domain) => strtolower(trim($domain)),
        explode(',', (string) env('TENANCY_CENTRAL_DOMAINS', ''))
    ),
])));

return [
    'tenant_model' => App\Models\Tenant::class,
    'id_generator' => UUIDGenerator::class,

    'domain_model' => Domain::class,

    /**
     * The list of domains hosting your central app.
     *
     * Only relevant if you're using the domain or subdomain identification middleware.
     */
    'central_domains' => $centralDomains,

    // Parent domain used to build tenant hosts, for example example.com.
    // Leave blank when the installation does not use tenant subdomains.
    'parent_domain' => $parentDomain !== '' ? strtolower($parentDomain) : null,

    /**
     * Tenancy bootstrappers are executed when tenancy is initialized.
     * Their responsibility is making Laravel features tenant-aware.
     *
     * To configure their behavior, see the config keys below.
     */
    'bootstrappers' => [
        DatabaseTenancyBootstrapper::class,
        // CacheTenancyBootstrapper is deliberately OFF. It isolates tenants by
        // wrapping every call in ->tags(), which neither the file nor the
        // database driver supports — so any Cache:: call inside a 分站 threw
        // "This cache store does not support tagging" and took the page with
        // it (the customer-facing 套餐 page among them). Isolation is done
        // explicitly instead: cache keys carry the site, via SiteKey::scope().
        // Stancl\Tenancy\Bootstrappers\CacheTenancyBootstrapper::class,
        FilesystemTenancyBootstrapper::class,
        QueueTenancyBootstrapper::class,
        // Stancl\Tenancy\Bootstrappers\RedisTenancyBootstrapper::class, // Note: phpredis is needed
    ],

    /**
     * Database tenancy config. Used by DatabaseTenancyBootstrapper.
     */
    'database' => [
        'central_connection' => env('DB_CONNECTION', 'central'),

        /**
         * Connection used as a "template" for the dynamically created tenant database connection.
         * Note: don't name your template connection tenant. That name is reserved by package.
         */
        'template_tenant_connection' => null,

        /**
         * Tenant database names are created like this:
         * prefix + tenant_id + suffix.
         */
        'prefix' => 'tenant',
        'suffix' => '.sqlite', // 每个租户一个独立 SQLite 文件：tenant<uuid>.sqlite

        /**
         * TenantDatabaseManagers are classes that handle the creation & deletion of tenant databases.
         */
        'managers' => [
            'sqlite' => SQLiteDatabaseManager::class,
            'mysql' => MySQLDatabaseManager::class,
            'mariadb' => MySQLDatabaseManager::class,
            'pgsql' => PostgreSQLDatabaseManager::class,

        /**
         * Use this database manager for MySQL to have a DB user created for each tenant database.
         * You can customize the grants given to these users by changing the $grants property.
         */
            // 'mysql' => Stancl\Tenancy\TenantDatabaseManagers\PermissionControlledMySQLDatabaseManager::class,

        /**
         * Disable the pgsql manager above, and enable the one below if you
         * want to separate tenant DBs by schemas rather than databases.
         */
            // 'pgsql' => Stancl\Tenancy\TenantDatabaseManagers\PostgreSQLSchemaManager::class, // Separate by schema instead of database
        ],
    ],

    /**
     * Cache tenancy config. Used by CacheTenancyBootstrapper.
     *
     * This works for all Cache facade calls, cache() helper
     * calls and direct calls to injected cache stores.
     *
     * Each key in cache will have a tag applied on it. This tag is used to
     * scope the cache both when writing to it and when reading from it.
     *
     * You can clear cache selectively by specifying the tag.
     */
